-- Customer Invitations + human-friendly listing numbers

-- Every marketplace listing gets a stable, easy-to-share numeric number.
create sequence if not exists public.listing_number_seq start 10001;
alter table public.listings add column if not exists listing_number bigint;
update public.listings
set listing_number = nextval('public.listing_number_seq')
where listing_number is null;
alter table public.listings alter column listing_number set default nextval('public.listing_number_seq');
create unique index if not exists listings_listing_number_uidx on public.listings(listing_number);

create table if not exists public.customer_invitations (
  id bigint generated by default as identity primary key,
  phone text not null unique,
  status text not null default 'not_sent' check (status in ('not_sent','sent','do_not_contact')),
  sent_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.customer_invitations enable row level security;

drop policy if exists customer_invitations_admin_select on public.customer_invitations;
create policy customer_invitations_admin_select on public.customer_invitations for select to authenticated
using (exists (select 1 from public.admin_users a where a.user_id = auth.uid()));
drop policy if exists customer_invitations_admin_insert on public.customer_invitations;
create policy customer_invitations_admin_insert on public.customer_invitations for insert to authenticated
with check (exists (select 1 from public.admin_users a where a.user_id = auth.uid()));
drop policy if exists customer_invitations_admin_update on public.customer_invitations;
create policy customer_invitations_admin_update on public.customer_invitations for update to authenticated
using (exists (select 1 from public.admin_users a where a.user_id = auth.uid()))
with check (exists (select 1 from public.admin_users a where a.user_id = auth.uid()));
drop policy if exists customer_invitations_admin_delete on public.customer_invitations;
create policy customer_invitations_admin_delete on public.customer_invitations for delete to authenticated
using (exists (select 1 from public.admin_users a where a.user_id = auth.uid()));

